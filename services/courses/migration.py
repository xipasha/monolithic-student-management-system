"""Copy and compare legacy PostgreSQL course data without deleting source rows."""

from psycopg2 import sql
from psycopg2.extras import RealDictCursor


def _set_schema(connection, schema):
    with connection.cursor() as cursor:
        cursor.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(schema)))


def _legacy_rows(source, schema):
    _set_schema(source, schema)
    with source.cursor(cursor_factory=RealDictCursor) as cursor:
        cursor.execute(
            "SELECT id, course_code, course_name, description FROM courses ORDER BY id"
        )
        courses = [dict(row) for row in cursor.fetchall()]
        cursor.execute(
            """SELECT e.id, e.course_id, s.student_number, e.enrolled_at::text AS enrolled_at
               FROM enrolments e JOIN students s ON s.id = e.student_id ORDER BY e.id"""
        )
        enrolments = [dict(row) for row in cursor.fetchall()]
    return courses, enrolments


def _ensure_target_schema(target, schema):
    with target.cursor() as cursor:
        cursor.execute(sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(sql.Identifier(schema)))
    target.commit()
    _set_schema(target, schema)
    with target.cursor() as cursor:
        cursor.execute(
            """CREATE TABLE IF NOT EXISTS courses (
                 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                 course_code TEXT NOT NULL UNIQUE,
                 course_name TEXT NOT NULL,
                 description TEXT NOT NULL DEFAULT ''
               )"""
        )
        cursor.execute(
            """CREATE TABLE IF NOT EXISTS enrolments (
                 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                 course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
                 student_number TEXT NOT NULL,
                 enrolled_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
                 UNIQUE (course_id, student_number)
               )"""
        )
    target.commit()


def migrate_course_data(source, target, source_schema="public", target_schema="courses"):
    """Idempotently insert missing source IDs, reject conflicts, reseed identities."""
    courses, enrolments = _legacy_rows(source, source_schema)
    _ensure_target_schema(target, target_schema)
    _set_schema(target, target_schema)
    with target.cursor() as cursor:
        for course in courses:
            cursor.execute(
                """INSERT INTO courses (id, course_code, course_name, description)
                   VALUES (%s, %s, %s, %s) ON CONFLICT (id) DO NOTHING""",
                (course["id"], course["course_code"], course["course_name"], course["description"]),
            )
        for enrolment in enrolments:
            cursor.execute(
                """INSERT INTO enrolments (id, course_id, student_number, enrolled_at)
                   VALUES (%s, %s, %s, %s) ON CONFLICT (id) DO NOTHING""",
                (
                    enrolment["id"], enrolment["course_id"],
                    enrolment["student_number"], enrolment["enrolled_at"],
                ),
            )
        cursor.execute(
            "SELECT setval(pg_get_serial_sequence('courses', 'id'), "
            "COALESCE(MAX(id), 1), MAX(id) IS NOT NULL) FROM courses"
        )
        cursor.execute(
            "SELECT setval(pg_get_serial_sequence('enrolments', 'id'), "
            "COALESCE(MAX(id), 1), MAX(id) IS NOT NULL) FROM enrolments"
        )
    target.commit()
    mismatches = compare_course_data(source, target, source_schema, target_schema)
    if mismatches:
        raise ValueError(f"Migration comparison found {len(mismatches)} mismatch(es): {mismatches[:10]}")
    return {"courses": len(courses), "enrolments": len(enrolments), "mismatches": []}


def compare_course_data(source, target, source_schema="public", target_schema="courses"):
    source_courses, source_enrolments = _legacy_rows(source, source_schema)
    _set_schema(target, target_schema)
    with target.cursor(cursor_factory=RealDictCursor) as cursor:
        cursor.execute(
            "SELECT id, course_code, course_name, description FROM courses ORDER BY id"
        )
        target_courses = [dict(row) for row in cursor.fetchall()]
        cursor.execute(
            "SELECT id, course_id, student_number, enrolled_at::text AS enrolled_at "
            "FROM enrolments ORDER BY id"
        )
        target_enrolments = [dict(row) for row in cursor.fetchall()]
    mismatches = []
    for label, left, right in (
        ("courses", source_courses, target_courses),
        ("enrolments", source_enrolments, target_enrolments),
    ):
        source_map = {row["id"]: row for row in left}
        target_map = {row["id"]: row for row in right}
        for record_id in sorted(source_map.keys() | target_map.keys()):
            if source_map.get(record_id) != target_map.get(record_id):
                mismatches.append(
                    {"table": label, "id": record_id,
                     "source": source_map.get(record_id), "target": target_map.get(record_id)}
                )
    return mismatches
